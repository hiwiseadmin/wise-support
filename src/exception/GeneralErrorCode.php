<?php
declare(strict_types=1);

namespace wise\support\exception;

/**
 * 框架级通用错误码（100~999）
 *
 * 涵盖所有 wise-* 包和 app 层共用的 HTTP 语义错误、基础设施错误。
 * 各 wise-* 包通过自有 ErrorCode 枚举（10000 起，每个包独立号段）定义领域专属码，
 * 本枚举仅提供"跨包通用"的码。
 *
 * 编码规则：号段内按语义分组，不加密、见名知意。
 *
 * @package wise\support\exception
 */
enum GeneralErrorCode: int
{
    // ============================================================
    // HTTP 语义错误 (100~199)
    // ============================================================

    /** 请求参数错误 */
    case BAD_REQUEST          = 100;

    /** 未认证 / 未登录 */
    case UNAUTHORIZED         = 101;

    /** 权限不足 */
    case FORBIDDEN            = 102;

    /** 资源不存在 */
    case NOT_FOUND            = 103;

    /** 请求方法不允许 */
    case METHOD_NOT_ALLOWED   = 104;

    /** 请求过于频繁 */
    case TOO_MANY_REQUESTS    = 105;

    /** 服务器内部错误 */
    case SERVER_ERROR         = 150;

    /** 服务暂不可用 */
    case SERVICE_UNAVAILABLE  = 151;

    // ============================================================
    // 校验错误 (200~299)
    // ============================================================

    /** 通用校验失败 */
    case VALIDATION_FAILED    = 200;

    /** 必填字段缺失 */
    case REQUIRED_FIELD       = 201;

    /** 字段格式无效 */
    case INVALID_FORMAT       = 202;

    // ============================================================
    // 基础设施错误 (300~399)
    // ============================================================

    /** 配置缺失或无效 */
    case CONFIG_ERROR         = 300;

    /** 数据库错误 */
    case DB_ERROR             = 301;

    /** 缓存错误 */
    case CACHE_ERROR          = 302;

    /** 文件/IO 错误 */
    case IO_ERROR             = 303;

    /** 网络请求失败 */
    case NETWORK_ERROR        = 304;

    /** 第三方服务不可用 */
    case THIRD_PARTY_ERROR    = 305;

    /** 扩展点/依赖未注册 */
    case EXT_POINT_NOT_DEFINED = 306;

    // ============================================================
    // 预留 app 层业务通用码 (400~899)
    // 以下仅定义号段边界，具体枚举由 app 自行扩展
    // ============================================================

    // 900~999 预留未来扩展
}
